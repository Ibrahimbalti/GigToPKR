import { formatBreakdownText } from "@/lib/calculator";
import { RESULT_DISCLAIMER } from "@/lib/constants";
import type { CalculatorResult } from "@/types/calculator";

function escapePdfText(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/\(/g, "\\(").replace(/\)/g, "\\)");
}

function buildPdf(lines: string[]): Uint8Array {
  const content = [
    "BT",
    "/F1 16 Tf",
    "50 800 Td",
    `(${escapePdfText(lines[0] ?? "GigToPKR")}) Tj`,
    "/F1 11 Tf",
    ...lines.slice(1).map((line, index) => {
      const y = 770 - index * 16;
      return `1 0 0 1 50 ${y} Tm (${escapePdfText(line)}) Tj`;
    }),
    "ET",
  ].join("\n");

  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Count 1 /Kids [3 0 R] >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${content.length} >>\nstream\n${content}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
  ];

  let pdf = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(pdf.length);
    pdf += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n`;
  pdf += "0000000000 65535 f \n";
  for (let index = 1; index < offsets.length; index += 1) {
    pdf += `${String(offsets[index]).padStart(10, "0")} 00000 n \n`;
  }
  pdf += `trailer << /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new TextEncoder().encode(pdf);
}

export function buildBreakdownPdf(result: CalculatorResult): Uint8Array {
  const lines = [
    ...formatBreakdownText(result).split("\n"),
    RESULT_DISCLAIMER,
    "Generated by GigToPKR for personal estimation.",
  ];
  return buildPdf(lines.slice(0, 28));
}

export function downloadPdf(filename: string, bytes: Uint8Array): void {
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  const blob = new Blob([copy.buffer], { type: "application/pdf" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  link.click();
  URL.revokeObjectURL(url);
}
